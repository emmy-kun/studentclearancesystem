// Application letter: "Application for the Collection of My Statement of Results and
// Original Degree Certificate", addressed to the Office of the Deputy Registrar and filled
// in from the student record. It is generated when the departmental officer verifies the
// student's name on the graduation list (approving stage 7), and mentions where it appears.
import { writePdf, longDate, titleCase } from './pdfFiles.js';
import brand from '../config/brand.js';

const SUBJECT = 'APPLICATION FOR THE COLLECTION OF MY STATEMENT OF RESULTS AND ORIGINAL DEGREE CERTIFICATE';

/** Best address we have for the student: the Security details form, else the accommodation form. */
function studentAddress(ctx) {
  const security = ctx.stages.find((s) => s.stage_key === 'security')?.form_data;
  const affairs = ctx.stages.find((s) => s.stage_key === 'student_affairs')?.form_data;
  if (security?.hostel_or_address) return security.hostel_or_address;
  if (affairs?.off_campus_address) return affairs.off_campus_address;
  if (affairs?.hostel_name) return [affairs.hostel_name, affairs.room_no && `Room ${affairs.room_no}`].filter(Boolean).join(', ');
  return null;
}

export function drawLetter(doc, { student, session, address, phone, date, listing }) {
  const name = titleCase(student.full_name);
  const right = { align: 'right', width: doc.page.width - 112 };

  // Sender's address block (top right)
  doc.font('Helvetica').fontSize(11);
  doc.text(`Department of ${student.department},`, right);
  doc.text(`Faculty of ${student.faculty},`, right);
  if (brand.institution) doc.text(`${brand.institution}.`, right);
  if (address) doc.text(address, right);
  doc.moveDown(0.5).text(longDate(date), right);

  // Recipient
  doc.moveDown(1.5);
  doc.text('The Deputy Registrar,');
  doc.text(brand.institution ? 'Office of the Deputy Registrar,' : 'Office of the Deputy Registrar.');
  if (brand.institution) doc.text(`${brand.institution}.`);

  doc.moveDown(1.2).text('Dear Sir/Ma,');

  doc.moveDown(0.8).font('Helvetica-Bold').text(SUBJECT, { align: 'center', underline: true });

  doc.moveDown(0.8).font('Helvetica').fontSize(11.5);
  const para = { align: 'justify', lineGap: 3, paragraphGap: 8 };
  doc.text(
    `I, ${name}, with Registration Number ${student.matric_no}, a graduating student of the Department of ` +
      `${student.department}, Faculty of ${student.faculty}, in the ${session} academic session, humbly apply ` +
      'for the collection of my Statement of Results and my Original Degree Certificate.',
    para
  );
  if (listing?.page_no) {
    doc.text(
      `My name appears on the graduation list for the ${session} session on page ${listing.page_no}${listing.serial_no ? `, number ${listing.serial_no}` : ''}, ` +
        'and this has been verified by my department.',
      para
    );
  }
  doc.text(
    'I have completed the final-year clearance procedure of the University, including departmental, faculty, ' +
      "library, alumni, accommodation, security and convocation clearance. My clearance records are held on the " +
      'University clearance system and can be checked against my registration number.',
    para
  );
  doc.text('I would be grateful if my request is granted.', para);
  doc.text('Thank you.', para);

  doc.moveDown(1).text('Yours faithfully,');
  doc.moveDown(2.2);
  doc.text('______________________________');
  doc.font('Helvetica-Bold').text(name.toUpperCase());
  doc.font('Helvetica').text(`Reg. No.: ${student.matric_no}`);
  if (phone) doc.text(`Phone: ${phone}`);
  doc.text(`Email: ${student.email}`);

  doc.fontSize(8).fillColor('#666')
    .text(`Generated by the ${brand.name} on ${longDate(date)}.`, 56, doc.page.height - 70, { align: 'center', width: doc.page.width - 112 });
}

/**
 * Create the letter inside the transaction that approves the graduation-list stage.
 * Returns { file_path, replaced_path } so the caller can tidy up files.
 */
export async function createLetter(conn, ctx) {
  const security = ctx.stages.find((st) => st.stage_key === 'security')?.form_data;
  const listing = ctx.stages.find((st) => st.stage_key === 'letter')?.form_data;
  const [[extra]] = await conn.query('SELECT phone FROM students WHERE student_id = ?', [ctx.student.student_id]);
  const filePath = await writePdf('letters', (doc) =>
    drawLetter(doc, {
      student: ctx.student,
      session: ctx.request.session,
      address: studentAddress(ctx),
      phone: security?.phone || extra.phone,
      date: new Date(),
      listing,
    })
  );
  await conn.query('UPDATE clearance_requests SET letter_path = ? WHERE request_id = ?', [filePath, ctx.request.request_id]);
  return { file_path: filePath, replaced_path: ctx.request.letter_path || null };
}
